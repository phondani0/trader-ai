"""
Core data models for the trading bot.
All data structures used across the system are defined here.
"""

from __future__ import annotations

import enum
from datetime import datetime
from typing import Optional

from pydantic import BaseModel, Field


class StrategyType(str, enum.Enum):
    TREND_FOLLOWING = "trend_following"
    MEAN_REVERSION = "mean_reversion"
    SCALPING = "scalping"
    UNKNOWN = "unknown"


# ─── Enums ────────────────────────────────────────────────────────────

class Side(str, enum.Enum):
    BUY = "buy"
    SELL = "sell"


class OrderType(str, enum.Enum):
    MARKET = "market"
    LIMIT = "limit"
    STOP = "stop"
    STOP_LIMIT = "stop_limit"
    TRAILING_STOP = "trailing_stop"


class OrderStatus(str, enum.Enum):
    PENDING = "pending"
    FILLED = "filled"
    PARTIALLY_FILLED = "partially_filled"
    CANCELLED = "cancelled"
    REJECTED = "rejected"
    EXPIRED = "expired"


class SignalType(str, enum.Enum):
    STRONG_BUY = "strong_buy"
    BUY = "buy"
    NEUTRAL = "neutral"
    SELL = "sell"
    STRONG_SELL = "strong_sell"


class MarketRegime(str, enum.Enum):
    TRENDING_LOW_VOL = "trending_low_vol"
    TRENDING_HIGH_VOL = "trending_high_vol"
    SIDEWAYS_LOW_VOL = "sideways_low_vol"
    SIDEWAYS_HIGH_VOL = "sideways_high_vol"
    UNKNOWN = "unknown"


class MarketBias(str, enum.Enum):
    BULLISH = "bullish"
    BEARISH = "bearish"
    NEUTRAL = "neutral"


class RegimeState(BaseModel):
    """Combined context of market regime and macro bias."""
    regime: MarketRegime
    bias: MarketBias
    is_burst: bool = False
    is_sweep: bool = False


class TradingMode(str, enum.Enum):
    PAPER = "paper"
    LIVE = "live"


# ─── Data Models ──────────────────────────────────────────────────────

class Candle(BaseModel):
    """Single OHLCV candle."""
    timestamp: datetime
    open: float
    high: float
    low: float
    close: float
    volume: float
    vwap: Optional[float] = None


class Signal(BaseModel):
    """Trading signal generated by a strategy."""
    timestamp: datetime
    symbol: str
    strategy_name: str
    signal_type: SignalType
    side: Side
    entry_price: float
    stop_loss: float
    take_profit: Optional[float] = None
    confidence: float = Field(ge=0.0, le=1.0, description="Signal confidence 0-1")
    regime: MarketRegime = MarketRegime.UNKNOWN
    reason: str = ""
    metadata: dict = Field(default_factory=dict)


class Order(BaseModel):
    """Order to be placed with the broker."""
    id: Optional[str] = None
    timestamp: datetime = Field(default_factory=datetime.utcnow)
    symbol: str
    side: Side
    quantity: float
    order_type: OrderType = OrderType.MARKET
    limit_price: Optional[float] = None
    stop_price: Optional[float] = None
    status: OrderStatus = OrderStatus.PENDING
    filled_price: Optional[float] = None
    filled_quantity: Optional[float] = None
    strategy_name: str = ""
    signal: Optional[Signal] = None


class Position(BaseModel):
    """Current open position."""
    symbol: str
    side: Side
    quantity: float
    entry_price: float
    current_price: float = 0.0
    stop_loss: float = 0.0
    take_profit: Optional[float] = None
    unrealized_pnl: float = 0.0
    unrealized_pnl_pct: float = 0.0
    strategy_name: str = ""
    entry_time: datetime = Field(default_factory=datetime.utcnow)

    def update_pnl(self, current_price: float):
        """Recalculate unrealized P&L based on current price."""
        self.current_price = current_price
        if self.side == Side.BUY:
            self.unrealized_pnl = (current_price - self.entry_price) * self.quantity
        else:
            self.unrealized_pnl = (self.entry_price - current_price) * self.quantity
        if self.entry_price > 0 and self.quantity > 0:
            self.unrealized_pnl_pct = (self.unrealized_pnl / (self.entry_price * self.quantity)) * 100
        else:
            self.unrealized_pnl_pct = 0.0


class Trade(BaseModel):
    """Completed trade (entry + exit)."""
    id: Optional[int] = None
    symbol: str
    side: Side
    quantity: float
    entry_price: float
    exit_price: float
    entry_time: datetime
    exit_time: datetime
    strategy_name: str
    pnl: float = 0.0
    pnl_pct: float = 0.0
    regime: MarketRegime = MarketRegime.UNKNOWN
    reason_entry: str = ""
    reason_exit: str = ""

    def calculate_pnl(self):
        """Calculate realized P&L."""
        if self.side == Side.BUY:
            self.pnl = (self.exit_price - self.entry_price) * self.quantity
        else:
            self.pnl = (self.entry_price - self.exit_price) * self.quantity
        if self.entry_price > 0 and self.quantity > 0:
            self.pnl_pct = (self.pnl / (self.entry_price * self.quantity)) * 100
        else:
            self.pnl_pct = 0.0


class DailySummary(BaseModel):
    """End-of-day trading summary."""
    date: datetime
    total_trades: int = 0
    winning_trades: int = 0
    losing_trades: int = 0
    gross_pnl: float = 0.0
    total_commission: float = 0.0
    net_pnl: float = 0.0
    win_rate: float = 0.0
    max_drawdown: float = 0.0
    sharpe_ratio: Optional[float] = None
    regime_distribution: dict = Field(default_factory=dict)
    strategy_pnl: dict = Field(default_factory=dict)
